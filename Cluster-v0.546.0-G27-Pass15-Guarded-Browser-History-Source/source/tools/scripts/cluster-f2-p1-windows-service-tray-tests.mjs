import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname,'../..');
const read = f => readFileSync(path.join(root,f),'utf8');
const svc=read('apps/server-launcher-go/windows_service.go');
const actions=read('apps/server-launcher-go/service_actions_windows.go');
const main=read('apps/server-launcher-go/main.go');
const gui=read('apps/server-launcher-go/launcher_ui_windows.go');
const settings=read('apps/server-launcher-go/server_config_windows.go');
const installer=read('tools/windows/Install-ClusterNativeService.ps1');
let count=0;
function check(b,label){assert.ok(b,label);count++}
check(svc.startsWith('//go:build windows'),'Windows-only native service code');
check(svc.includes('StartServiceCtrlDispatcherW'),'connects to Windows SCM dispatcher');
check(svc.includes('RegisterServiceCtrlHandlerExW'),'registers service control handler');
check(svc.includes('SetServiceStatus'),'reports SCM service status');
check(svc.includes('OpenSCManagerW') && svc.includes('CreateServiceW'),'native service creation');
check(svc.includes('QueryServiceStatusEx'),'service state/Process ID query');
check(svc.includes('ControlService') && svc.includes('StartServiceW'),'native start and stop');
check(svc.includes('serviceControlStop') && svc.includes('serviceControlShutdown'),'handles OS stop/shutdown signals');
check(svc.includes('context.WithCancel') && svc.includes('cancel()'),'cancelable service lifetime');
check(svc.includes('managedHostStopGrace'),'graceful host drain deadline');
check(svc.includes('processjob.New()') && svc.includes('job.Close()'),'kernel-owned whole-tree process termination');
check(svc.includes('runServiceManaged(ctx, root, func()'),'service waits for explicit application readiness');
check(svc.includes('windows-service.control'),'dedicated service control file');
check(svc.includes('serviceRuntimePrerequisites(root)'),'prebuilt runtime prerequisites');
check(svc.includes('releasePrebuiltReady(root)'),'enforces matching prebuilt release');
check(svc.includes('windows-service-ready.marker'),'explicit provisioning gate');
check(svc.includes('NT AUTHORITY\\LocalService'),'least-privileged service account');
check(!svc.includes('NT AUTHORITY\\SYSTEM') && !svc.includes('ptr("LocalSystem")'),'no LocalSystem service account');
check(svc.includes('serviceAutoStart'),'SCM automatic boot startup');
check(svc.includes('HostUnexpectedExit'),'unexpected host exits create native emergencies');
check(svc.includes('ctx.Err() == nil'),'operator-initiated stop not treated as crash');
check(actions.includes('ensureWindowsAdministrator'),'admin gate for SCM install/remove');
check(actions.includes('runWindowsService(root)'),'service mode bypasses interactive GUI');
check(main.includes('"service-install"') && main.includes('"service-remove"') && main.includes('"service"'),'CLI exposes separate service lifecycle modes');
check(main.includes('runPlatformServiceAction(root'),'CLI routes service mode before GUI elevation');
check(gui.includes('refreshServiceState()'),'control panel attaches to installed service');
check(gui.includes('startClusterService()') && gui.includes('stopClusterService()'),'GUI uses SCM start/stop');
check(gui.includes('waitClusterService(serviceStopped'),'SCM-based restart waits for stop');
check(gui.includes('if managed {') && gui.includes('procDestroyWindow.Call(ui.hwnd)'),'service-aware UI exit');
check(gui.includes('Shell_NotifyIconW'),'native system tray icon');
check(gui.includes('TaskbarCreated'),'tray restored after Explorer restart');
check(gui.includes('wmAppTray') && gui.includes('wmLButtonDblclk'),'tray restoration events');
check(gui.includes('showTrayMenu()') && gui.includes('idTrayExit'),'separate tray exit action');
check(gui.includes('ConfirmStop()') && gui.includes('ConfirmRestart()'),'explicit stop/restart confirmation');
check(gui.includes('swpNoMove|swpNoSize|swpNoActivate'),'always-on-top does not relocate panel');
for(const key of ['AlwaysOnTop','MinimizeToTray','CloseToTray','StartMinimized','StartWithWindows'])check(settings.includes(key),`persisted operator preference ${key}`);
check(installer.includes("IsInRole"),'PowerShell requires administrator');
check(installer.includes('*S-1-5-19:(OI)(CI)RX'),'LocalService read-only binary ACL');
check(installer.includes('*S-1-5-19:(OI)(CI)M'),'LocalService limited data/runtime write ACL');
check(installer.includes('failureflag ClusterStudioServer 1'),'bounded SCM recovery policy');
check(installer.includes('reset= 86400 actions= restart/60000/restart/120000/none/0'),'SCM recovery cooldown and cap');
check(installer.includes('SupportsShouldProcess'),'PowerShell -WhatIf support');
console.log(`Cluster F2 P1 Native Service/Tray contract: ${count}/${count} assertions passed`);
