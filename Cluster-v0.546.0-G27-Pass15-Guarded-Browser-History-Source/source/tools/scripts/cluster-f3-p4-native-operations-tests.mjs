import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const read = file => readFileSync(path.join(root,file),'utf8');
const journal = read('apps/native-alerts-go/alerts.go');
const host = read('apps/host-go/main.go');
const process = read('apps/host-go/api_process.go');
const readiness = read('apps/host-go/native_readiness_watch.go');
const launcher = read('apps/server-launcher-go/main.go');
const panel = read('apps/server-launcher-go/launcher_ui_windows.go');
const hostModule = read('apps/host-go/go.mod');
const launcherModule = read('apps/server-launcher-go/go.mod');
const toolVersions = read('tools/scripts/toolchain-versions.mjs');
let count = 0;
function check(predicate, label) { assert.ok(predicate,label); count++; }
check(journal.includes('module') === false || journal.includes('package nativealerts'), 'shared Go package');
check(journal.includes('func (s *Spool) Emit'), 'native event emission');
check(journal.includes('os.O_CREATE|os.O_EXCL|os.O_WRONLY'), 'exclusive file creation');
check(journal.includes('file.Sync()'), 'event data flush');
check(journal.includes('nativeAlertMaxPending'), 'bounded pending journal');
check(journal.includes('nativeAlertMaxSent'), 'bounded sent history');
check(journal.includes('func (s *Spool) reclaimStaleClaims'), 'crash recovery for claimed events');
check(journal.includes('".sending"'), 'cross-process delivery claim');
check(journal.includes('".invalid"'), 'malformed events quarantined');
check(journal.includes('nativeAlertDedupInterval'), 'duplicate suppression');
check(journal.includes('s.webhookURL == ""'), 'outbound delivery opt-in');
check(journal.includes('u.Hostname() != "discord.com"'), 'transport allowlist');
check(journal.includes('u.Scheme != "https"'), 'HTTPS required');
check(journal.includes('http.ErrUseLastResponse'), 'webhook redirects disabled');
check(journal.includes('"allowed_mentions"'), 'no unwanted Discord mentions');
check(!journal.includes('CLUSTER_DATABASE_URL'), 'no database secret dependency');
check(host.includes('newNativeAlertSpool') === false && host.includes('nativealerts.New'), 'host shared integration');
check(process.includes('nativealerts.APICrashed'), 'API crash coverage');
check(process.includes('nativealerts.APIRecoveryFailed'), 'restart exhaustion alert');
check(process.includes('nativealerts.APIRecovered'), 'restart recovery alert');
check(host.includes('nativealerts.APIReadinessFailed'), 'initial API readiness failure alert');
check(host.includes('nativealerts.GatewayBindFailed'), 'gateway bind failure alert');
check(readiness.includes('30*time.Second') || readiness.includes('30 * time.Second'), 'readiness reconciled every 30s');
check(readiness.includes('r.failed >= 2') && readiness.includes('r.passed >= 2'), 'consecutive state thresholds');
check(readiness.includes('"/health/supervisor"'), 'reuse maintenance-safe supervisor readiness endpoint');
check(launcher.includes('recordLauncherEmergency(root, nativealerts.LauncherStartupFailed)'), 'headless launcher failure');
check(panel.includes('nativealerts.HostReadinessTimeout'), 'host watchdog failure alert');
check(panel.includes('nativealerts.HostUnexpectedExit'), 'host exit alert');
check(panel.includes('"Stop Cluster Server"') && panel.includes('"Restart Cluster Server"'), 'native stop and restart confirmation');
check(/replace\s+cluster\.local\/native-alerts\s+=>\s+\.\.\/native-alerts-go/.test(hostModule), 'host local module reference');
check(/replace\s+cluster\.local\/native-alerts\s+=>\s+\.\.\/native-alerts-go/.test(launcherModule), 'launcher local module reference');
check(toolVersions.includes('apps/native-alerts-go/go.mod'), 'module toolchain pin synchronized');
console.log(`Cluster F3 P4 Native Alerts and Windows Operations Integration: ${count}/${count} checks passed`);
