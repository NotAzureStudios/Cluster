import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const input = path.join(root, 'packages/shared/appearance/semantic-palette.json');
const output = path.join(root, 'apps/desktop-qt/qml/ThemeTokens.qml');
const palette = JSON.parse(fs.readFileSync(input, 'utf8'));
const keys = Object.keys(palette.dark);
if (keys.length === 0 || Object.keys(palette.light).sort().join('|') !== keys.slice().sort().join('|')) {
  throw Error('Appearance modes must declare exactly the same semantic keys');
}
const lines = [
  '// GENERATED by tools/scripts/generate-appearance-qt-tokens.mjs; do not edit.',
  '// CSS #RRGGBBAA is converted to Qt #AARRGGBB.',
  'pragma Singleton',
  'import QtQuick',
  '',
  'QtObject {',
];
for (const key of keys) {
  if (!/^[a-z][a-zA-Z0-9]*$/.test(key)) throw Error(`Invalid semantic key: ${key}`);
  for (const mode of ['dark','light']) {
    const raw = palette[mode][key];
    if (typeof raw !== 'string' || !/^#(?:[a-f0-9]{6}|[a-f0-9]{8})$/i.test(raw)) {
      throw Error(`Invalid CSS hex for ${mode}.${key}`);
    }
    const qt = raw.length === 9 ? `#${raw.slice(7)}${raw.slice(1,7)}` : raw;
    lines.push(`    readonly property color ${key}${mode === 'dark' ? 'Dark' : 'Light'}: "${qt.toUpperCase()}"`);
  }
}
lines.push('}', '');
const expected = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== expected) {
    console.error('Qt appearance tokens are stale. Run npm run appearance:generate:qt');
    process.exitCode = 1;
  } else console.log(`PASS Generated Qt token parity (${keys.length} keys x 2 modes)`);
} else {
  fs.writeFileSync(output, expected);
  console.log(`Wrote ${path.relative(root, output)} (${keys.length} keys x 2 modes)`);
}
