import assert from 'node:assert/strict';
import {readFileSync, existsSync} from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname,'../..');
const read = f => readFileSync(path.join(root,f),'utf8');
const job = read('apps/native-process-job-go/job_windows.go');
const launcher = read('apps/server-launcher-go/launcher_ui_windows.go');
const service = read('apps/server-launcher-go/windows_service.go');
const host = read('apps/host-go/api_process.go');
const hostMain = read('apps/host-go/main.go');
const postgres = read('apps/server-launcher-go/runtime_windows.go');
const ready = read('apps/host-go/service_readiness.go');
const readyTests = read('apps/host-go/service_readiness_test.go');
let n=0;
function check(v, message) {assert.ok(v,message);n++}
check(job.startsWith('//go:build windows'),'Job Objects only on Windows');
check(job.includes('CreateJobObjectW'),'job created through kernel32');
check(job.includes('SetInformationJobObject'),'job kernel limit configuration');
check(job.includes('jobObjectLimitKillOnJobClose'),'descendants killed on owner close');
check(job.includes('AssignProcessToJobObject'),'actual child process assignment');
check(job.includes('OpenProcess'),'subprocess handle acquisition');
check(job.includes('processSetQuota|processTerminate|processQueryLimitedInformation'),'least necessary process rights');
check(job.includes('defer closeHandle.Call(process)'),'process handle not leaked');
check(job.includes('QueryInformationJobObject'),'job accounting for persistent database');
check(job.includes('func (j *Job) ActiveProcesses()'),'database remains bound after pg_ctl exits');
check(job.includes('func (j *Job) Close()'),'owner explicitly releases job');
check(job.includes('j.mu.Lock()'),'concurrent supervisor close serialized');
check(job.includes('if handle == 0'),'idempotent Close');
check(existsSync(path.join(root,'apps/native-process-job-go/job_windows_test.go')),'Windows-native job tests exist');
check(host.includes('job, err := processjob.New()'),'API receives dedicated job');
check(host.includes('job.Assign(cmd)'),'API node process assigned');
check(host.includes('cmd.Process.Kill()') && host.includes('cmd.Wait()'),'API refuses unmanaged spawn');
check(host.includes('h.closeAPIJob()'),'API recovery kills orphaned descendants');
check(host.includes('defer h.closeAPIJob()'),'API graceful shutdown closes job');
check(service.includes('job, err := processjob.New()'),'SCM Host gets its own job');
check(service.includes('job.Assign(cmd)'),'SCM Host job assigned');
check(service.includes('defer job.Close()'),'SCM Host job guaranteed cleanup');
check(service.includes('case <-time.After(managedHostStopGrace)') && service.includes('_ = job.Close()'),'forced SCM shutdown via job');
check(/hostJob\s+\*processjob\.Job/.test(launcher),'GUI maintains independent Host job');
check(launcher.includes('job.Assign(cmd)'),'GUI attaches Host to job');
check(launcher.includes('_ = job.Close()'),'GUI teardown kills orphaned children');
check(postgres.includes('pgJob, err := processjob.New()'),'PostgreSQL owns persistent job');
check(postgres.includes('pgJob.Assign(startCmd)'),'pg_ctl is attached before waiting for server');
check(postgres.includes('pgJob.ActiveProcesses()'),'Postgres verifies persistent job-owned process');
check(postgres.includes('return databaseConfig{}, nil, fmt.Errorf("PostgreSQL spawned no job-owned server process'),'fails closed on detached PostgreSQL');
check(postgres.includes('stopPostgres(); err != nil'),'normal database shutdown requested first');
check(postgres.includes('pgJob.Close()'),'PostgreSQL job cleanup on success/failure');
check(!service.includes('"taskkill.exe"'),'SCM no longer relies on taskkill process enumeration');
check(!launcher.includes('"taskkill.exe"'),'GUI no longer relies on taskkill process enumeration');
check(service.includes('windows-service.ready'),'unique ready marker owned by service');
check(service.includes('_ = os.Remove(readyFile)'),'old readiness marker invalidated');
check(service.includes('Host did not publish confirmed readiness within 90 seconds'),'bounded readiness handshake');
check(service.includes('onReady()'),'RUNNING signaled after readiness');
check(service.includes('serviceStartPending'),'startup check-in state');
check(service.includes('previous != serviceStartPending'),'late startup signals cannot overwrite running/stopping');
check(hostMain.includes('publishServiceReadiness(readyFile)'),'host signals after listener/API readiness');
check(ready.includes('os.CreateTemp'),'atomic private ready marker staging');
check(ready.includes('file.Chmod(0600)'),'private ready marker');
check(ready.includes('file.Sync()'),'ready evidence flushed');
check(ready.includes('os.Rename(file.Name(), path)'),'ready marker atomically published');
check(readyTests.includes('TestPublishServiceReadiness'),'behavioral host readiness test');
check(read('apps/host-go/go.mod').includes('cluster.local/native-process-job'),'host module linked');
check(read('apps/server-launcher-go/go.mod').includes('cluster.local/native-process-job'),'launcher module linked');
console.log(`Cluster F2 P2 Native Process Supervision: ${n}/${n} source contract checks passed`);
