import fs from "node:fs";

let passed = 0; let failed = 0;
const text = (path) => fs.readFileSync(path, "utf8");
const check = (label, ok) => { if (ok) { passed++; console.log(`PASS ${label}`); } else { failed++; console.error(`FAIL ${label}`); } };
const perf = text("packages/renderer/src/core/performance.ts");
const offline = text("packages/renderer/src/core/offline-runtime.ts");
const app = text("packages/renderer/src/features/application/ClusterApplication.tsx");
const shell = text("packages/renderer/src/features/application/modules/application-shell.tsx");
const contracts = text("packages/shared/src/api-contracts.ts");
const notes = text("RELEASE_NOTES_v0.422.0.md");
const doc = text("docs/PERFORMANCE_PHASE5_BASELINE.md");
check("API contract advanced", contracts.includes('version: "2026-08-02.63"'));
check("performance capability advertised", contracts.includes('"renderer-performance-baseline-v2"'));
check("startup classes are explicit", perf.includes('type StartupClass = "cold" | "warm" | "reload"'));
check("warm startup window is bounded", perf.includes("WARM_START_WINDOW_MS = 30 * 60 * 1000"));
check("startup first frame is recorded", perf.includes("startup-first-frame"));
check("startup navigation timing is summarized", perf.includes("domContentLoadedMs") && perf.includes("startupLoadMs"));
check("render commit counts are tracked", perf.includes("renderCommits") && perf.includes("renderUpdates") && perf.includes("renderNestedUpdates"));
check("render cost is summarized", perf.includes("averageActualMs") && perf.includes("maximumActualMs"));
check("performance remains export on demand", perf.includes("downloadPerformanceReport") && perf.includes("clusterPerformance"));
check("connectivity snapshot is compact", offline.includes("getOfflineConnectivitySnapshot") && offline.includes("snapshot.online ? 1 : 0"));
check("root uses connectivity selector", app.includes("getOfflineConnectivitySnapshot") && app.includes("connectivitySnapshot"));
check("root no longer consumes full sync snapshot", !app.includes("getOfflineSyncSnapshot"));
check("connectivity object is memoized", app.includes("const offlineConnectivity = useMemo"));
check("sidebar visible projects are memoized", shell.includes("const visibleProjects = useMemo"));
check("sidebar pinned projects are memoized", shell.includes("const pinnedProjects = useMemo"));
check("sidebar ordered projects are memoized", shell.includes("const sidebarProjects = useMemo"));
check("existing render p95 budget retained", perf.includes('{ category: "render", p95Ms: 120'));
check("phase documentation exists", doc.includes("Phase 5 performance baseline") && doc.includes("Subscription isolation"));
check("release notes identify phase", notes.includes("Phase 5.1-5.7") && notes.includes("renderer-performance-baseline-v2"));
console.log(`Renderer performance Phase 5 audit: ${passed}/${passed + failed} passed.`);
if (failed) process.exit(1);
