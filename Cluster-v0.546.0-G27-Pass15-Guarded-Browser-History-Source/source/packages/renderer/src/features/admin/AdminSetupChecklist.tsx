import { DomainSetupContinuation } from "../domains/DomainSetupContinuation";
import { useCallback, useEffect, useRef, useState, type ChangeEvent } from "react";
import { ClusterButton } from "../../components/ClusterButton";
import { api, apiErrorPresentation } from "../../core/api";
import { useClusterActionFlight } from "../../components/useClusterActionFlight";
import { createClusterLatestResponse } from "../../components/cluster-action-flight";

type ChecklistEntry = {
  id: string;
  label: string;
  required: boolean;
  group: string; detail: string; nextStep: string; destination: string;
  status: "complete" | "recommended" | "skipped";
};
type ChecklistResponse = { ok: boolean; items: ChecklistEntry[]; complete: number; total: number; security: { ready: boolean; ownerCount: number; missingPasskeys: number; missingRecovery: number } };
type ConfigurationChange = { key: string; before: string | boolean | null; after: string | boolean | null };
type ConfigurationPreview = { ok: boolean; previewId: string; changes: ConfigurationChange[]; requestedCount: number };
type ConfigurationRevision = {
  id: string; actorUserId: string | null; createdAt: string;
  requested: Record<string, string | boolean>;
  changes: ConfigurationChange[];
};
type ConfigurationRevisionsResponse = { ok: boolean; revisions: ConfigurationRevision[] };
type ConfigurationRollbackPreview = { ok: boolean; revisionId: string; previewId: string; changes: ConfigurationChange[] };
const CONFIG_LABELS: Record<string, string> = {
  studioName: "Studio name", studioTimezone: "Studio timezone",
  defaultCreateStarterBoard: "Create starter Board",
  defaultCreateStarterWhiteboard: "Create starter Whiteboard",
  defaultCreateStarterLibrary: "Create starter Library folder",
};
function configurationValue(value: string | boolean | null) {
  if (value === null) return "Not configured";
  if (typeof value === "boolean") return value ? "Enabled" : "Disabled";
  return value;
}

/** A two-phase admin import. Preview is generated by the server, never by local guesses. */
function AdminConfigurationImport({ onApplied }: { onApplied: () => void }) {
  const [bundle, setBundle] = useState<unknown>(null);
  const [selectedKeys, setSelectedKeys] = useState<string[]>([]);
  const [fileName, setFileName] = useState("");
  const [preview, setPreview] = useState<ConfigurationPreview | null>(null);
  const [rollbackPreview, setRollbackPreview] = useState<ConfigurationRollbackPreview | null>(null);
  const [rollbackReason, setRollbackReason] = useState("");
  const { pending: actionPending, begin: beginAction, finish: finishAction } = useClusterActionFlight();
  const busy = actionPending !== null;
  const [revisions, setRevisions] = useState<ConfigurationRevision[]>([]);
  const revisionsGeneration = useRef(createClusterLatestResponse());
  const [revisionsError, setRevisionsError] = useState("");
  const refreshRevisions = useCallback(async () => {
    const revision = revisionsGeneration.current.next();
    try {
      const result = await api<ConfigurationRevisionsResponse>("/api/admin/setup/configuration/revisions");
      if (!revisionsGeneration.current.isCurrent(revision)) return;
      setRevisions(result.revisions); setRevisionsError("");
    } catch (cause) {
      if (revisionsGeneration.current.isCurrent(revision))
        setRevisionsError(apiErrorPresentation(cause).message || "Configuration history unavailable.");
    }
  }, []);
  useEffect(() => { void refreshRevisions(); return () => revisionsGeneration.current.invalidate(); }, [refreshRevisions]);
  const [feedback, setFeedback] = useState("");
  const [error, setError] = useState("");
  const generation = useRef(0);

  async function readFile(event: ChangeEvent<HTMLInputElement>) {
    const file = event.currentTarget.files?.[0];
    ++generation.current;
    setBundle(null); setSelectedKeys([]); setPreview(null); setRollbackPreview(null); setFileName(""); setFeedback(""); setError("");
    if (!file) return;
    const current = generation.current;
    try {
      if (file.size > 16_384) throw new Error("Configuration exceeds the 16 KiB limit.");
      const parsed: unknown = JSON.parse(await file.text());
      if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("Expected a configuration object.");
      const envelope = parsed as Record<string, unknown>;
      if (envelope.format !== "clusterconfig" || envelope.schemaVersion !== 1 ||
          Object.keys(envelope).some((key) => !["format", "schemaVersion", "settings"].includes(key))) {
        throw new Error("Only .clusterconfig schema 1 files without additional fields are supported.");
      }
      if (!envelope.settings || typeof envelope.settings !== "object" || Array.isArray(envelope.settings)) throw new Error("Configuration settings must be an object.");
      const keys = Object.keys(envelope.settings);
      if (keys.some((key) => !Object.prototype.hasOwnProperty.call(CONFIG_LABELS, key))) throw new Error("Configuration contains unsupported fields. No secrets or server settings can be imported.");
      if (current !== generation.current) return;
      setBundle(parsed); setSelectedKeys(keys); setFileName(file.name);
    } catch (cause) {
      if (current === generation.current) setError(cause instanceof Error ? cause.message : "Cannot read configuration file.");
    }
  }
  function selectedConfiguration(): unknown {
    if (!bundle || typeof bundle !== "object" || Array.isArray(bundle)) return null;
    const source = bundle as { format: string; schemaVersion: number; settings: Record<string, unknown> };
    return { format: source.format, schemaVersion: source.schemaVersion,
      settings: Object.fromEntries(Object.entries(source.settings).filter(([key]) => selectedKeys.includes(key))) };
  }
  function toggleField(key: string, included: boolean) {
    ++generation.current;
    setSelectedKeys((current) => included ? [...current, key] : current.filter((entry) => entry !== key));
    setPreview(null); setRollbackPreview(null); setFeedback(""); setError("");
  }
  async function inspect() {
    if (bundle === null || !selectedKeys.length || !beginAction("preview")) return;
    const current = generation.current; setPreview(null); setRollbackPreview(null); setFeedback(""); setError("");
    try {
      const result = await api<ConfigurationPreview>("/api/admin/setup/configuration/preview", {
        method: "POST", body: JSON.stringify({ configuration: selectedConfiguration() }),
      });
      if (current === generation.current) setPreview(result);
    } catch (cause) {
      if (current === generation.current) setError(apiErrorPresentation(cause).message || "Configuration preview failed.");
    } finally { finishAction("preview"); }
  }
  async function apply() {
    if (!preview || bundle === null || !selectedKeys.length || !preview.changes.length || !beginAction("apply")) return;
    const current = generation.current; setFeedback(""); setError("");
    try {
      const result = await api<{ ok: boolean; applied: number }>("/api/admin/setup/configuration/apply", {
        method: "POST", body: JSON.stringify({ configuration: selectedConfiguration(), previewId: preview.previewId }),
      });
      if (current === generation.current) {
        ++generation.current;
        setPreview(null); setBundle(null); setSelectedKeys([]); setFileName("");
        setFeedback(`${result.applied} studio setting${result.applied === 1 ? "" : "s"} imported. Security and server configuration were not modified.`);
        onApplied();
        void refreshRevisions();
      }
    } catch (cause) {
      if (current === generation.current) {
        setPreview(null); // A rejected or stale preview must never remain actionable.
        setError(apiErrorPresentation(cause).message || "Configuration import failed. Review the latest settings before retrying.");
      }
    } finally { finishAction("apply"); }
  }
  function reviewRevision(revision: ConfigurationRevision) {
    ++generation.current;
    setBundle({ format: "clusterconfig", schemaVersion: 1, settings: revision.requested });
    setSelectedKeys(Object.keys(revision.requested));
    setFileName(`Past import · ${new Date(revision.createdAt).toLocaleString()}`);
    setPreview(null); setRollbackPreview(null); setFeedback(""); setError("");
  }
  // Selective .clusterconfig imports cannot represent absent values. For
  // complete all-or-nothing restoration (including deletions), use the reviewed
  // rollback action below rather than guessing defaults.
  function reviewPriorValues(revision: ConfigurationRevision) {
    const prior = Object.fromEntries(revision.changes
      .filter((change) => Object.prototype.hasOwnProperty.call(CONFIG_LABELS, change.key) && (typeof change.before === "boolean" || (typeof change.before === "string" && !!change.before.trim())))
      .map((change) => [change.key, change.before]));
    ++generation.current;
    setBundle(Object.keys(prior).length ? { format: "clusterconfig", schemaVersion: 1, settings: prior } : null);
    setSelectedKeys(Object.keys(prior));
    setFileName(`Pre-import values · ${new Date(revision.createdAt).toLocaleString()}`);
    setPreview(null); setRollbackPreview(null); setFeedback("");
    setError(Object.keys(prior).length ? "" : "This revision does not contain reusable typed prior values. Use Preview rollback for safe restoration, including previously unset settings.");
  }
  async function inspectRollback(revision: ConfigurationRevision) {
    if (!beginAction("rollback-preview")) return;
    const current = ++generation.current; // An older import preview cannot survive a recovery review.
    setPreview(null); setRollbackPreview(null); setRollbackReason(""); setFeedback(""); setError("");
    try {
      const result = await api<ConfigurationRollbackPreview>(`/api/admin/setup/configuration/revisions/${encodeURIComponent(revision.id)}/rollback/preview`, {
        method: "POST", body: JSON.stringify({}),
      });
      if (current === generation.current) setRollbackPreview(result);
    } catch (cause) {
      if (current === generation.current) setError(apiErrorPresentation(cause).message || "Rollback cannot proceed. A later configuration change may conflict.");
    } finally { finishAction("rollback-preview"); }
  }
  async function applyRollback() {
    if (!rollbackPreview || rollbackReason.trim().length < 12 || !beginAction("rollback-apply")) return;
    const selected = rollbackPreview;
    setError(""); setFeedback("");
    try {
      const result = await api<{ ok: boolean; applied: number }>(`/api/admin/setup/configuration/revisions/${encodeURIComponent(selected.revisionId)}/rollback/apply`, {
        method: "POST", body: JSON.stringify({ previewId: selected.previewId, reason: rollbackReason.trim() }),
      });
      ++generation.current;
      setRollbackPreview(null); setRollbackReason(""); setBundle(null); setSelectedKeys([]); setPreview(null); setFileName("");
      setFeedback(`Reverted ${result.applied} studio default${result.applied === 1 ? "" : "s"}. A new revision was recorded.`);
      onApplied(); void refreshRevisions();
    } catch (cause) {
      setRollbackPreview(null); // Never permit replay of a rejected or stale preview.
      setError(apiErrorPresentation(cause).message || "Rollback was not applied. Generate a new preview.");
    } finally { finishAction("rollback-apply"); }
  }
  return <div className="admin-config-import-v506">
    <div><strong>Import studio defaults</strong><p className="muted tight">Review changes to the five safe studio settings before applying. No passwords, permissions, or server settings can be imported.</p></div>
    <label className="field"><span>Configuration file (.clusterconfig)</span>
      <input type="file" accept=".clusterconfig,.json,application/json" disabled={busy} onChange={(event) => void readFile(event)} />
    </label>
    {fileName && <p className="muted tight">Selected: {fileName}</p>}
    {bundle && typeof bundle === "object" && "settings" in bundle && <fieldset className="admin-config-selection-v509" disabled={busy}>
      <legend>Choose the defaults to import</legend>
      {Object.entries((bundle as { settings: Record<string, unknown> }).settings).map(([key, value]) => <label key={key}>
        <input type="checkbox" checked={selectedKeys.includes(key)} onChange={(event) => toggleField(key, event.target.checked)} />
        <span>{CONFIG_LABELS[key] || key} <small>{configurationValue(value as string | boolean | null)}</small></span>
      </label>)}
      <small>Unselected settings are not sent to the server. Changing selection clears the old preview; a fresh preview is required before applying.</small>
    </fieldset>}
    {error && <p role="alert" className="muted">{error}</p>}
    {feedback && <p role="status">{feedback}</p>}
    {preview && <div className="admin-config-preview-v506" aria-label="Configuration change preview">
      <strong>{preview.changes.length ? `${preview.changes.length} change(s) to review` : "No changes to apply"}</strong>
      {preview.changes.length > 0 && <ul>{preview.changes.map((change) => <li key={change.key}>
        <span>{CONFIG_LABELS[change.key] || change.key}</span>
        <small>{configurationValue(change.before)} → {configurationValue(change.after)}</small>
      </li>)}</ul>}
      <small>Only explicitly listed settings will change. Changes made by another administrator invalidate this preview.</small>
    </div>}
    <div className="button-row">
      <ClusterButton type="button" variant="secondary" size="compact" disabled={busy || bundle === null || !selectedKeys.length} aria-busy={actionPending === "preview"} onClick={() => void inspect()}>{actionPending === "preview" ? "Previewing…" : "Preview changes"}</ClusterButton>
      <ClusterButton type="button" variant="primary" size="compact" disabled={busy || !preview || preview.changes.length === 0} aria-busy={actionPending === "apply"} onClick={() => void apply()}>{actionPending === "apply" ? "Applying…" : "Apply reviewed settings"}</ClusterButton>
    </div>
    {rollbackPreview && <div className="admin-config-preview-v506" aria-label="Configuration rollback review">
      <strong>Review configuration rollback</strong>
      <p className="muted tight">Only these explicitly reviewed studio defaults will be restored. An unset previous value removes its override; no permissions, credentials or server settings are included. If any value changes before commit, the entire rollback is rejected.</p>
      <ul>{rollbackPreview.changes.map((change) => <li key={change.key}>
        <span>{CONFIG_LABELS[change.key] || change.key}</span>
        <small>{configurationValue(change.before)} → {configurationValue(change.after)}</small>
      </li>)}</ul>
      <label className="field"><span>Reason for reverting (required)</span>
        <textarea rows={2} maxLength={500} value={rollbackReason} disabled={busy}
          onChange={(event) => setRollbackReason(event.target.value)} placeholder="Explain why this configuration revision should be reversed" />
      </label>
      <div className="button-row">
        <ClusterButton type="button" variant="primary" size="compact" disabled={busy || rollbackReason.trim().length < 12} aria-busy={actionPending === "rollback-apply"}
          onClick={() => void applyRollback()}>{actionPending === "rollback-apply" ? "Restoring…" : "Apply reviewed rollback"}</ClusterButton>
        <ClusterButton type="button" variant="quiet" size="compact" disabled={busy} onClick={() => { setRollbackPreview(null); setRollbackReason(""); }}>Cancel rollback</ClusterButton>
      </div>
    </div>}
    <div className="admin-config-revisions-v506" aria-label="Recent configuration imports">
      <strong>Configuration revision history</strong>
      <p className="muted tight">Preview an exact, all-or-nothing rollback, including previously unset values. A later conflicting edit blocks restoration. Or copy historical values into a selective import.</p>
      {revisionsError && <p role="status" className="muted">{revisionsError}</p>}
      {revisions.length === 0 && !revisionsError && <p className="muted tight">No configuration revisions recorded yet.</p>}
      {revisions.map((revision) => <div className="admin-config-revision-v506" key={revision.id}>
        <span><strong>{new Date(revision.createdAt).toLocaleString()}</strong><small>{revision.changes.length} changed setting(s)</small></span>
        <div className="button-row">
          <ClusterButton type="button" variant="secondary" size="compact" disabled={busy || Object.keys(revision.requested).length === 0} onClick={() => reviewRevision(revision)}>Review imported values</ClusterButton>
          <ClusterButton type="button" variant="quiet" size="compact" disabled={busy} onClick={() => reviewPriorValues(revision)}>Review pre-import values</ClusterButton>
          <ClusterButton type="button" variant="secondary" size="compact" disabled={busy} aria-busy={actionPending === "rollback-preview"}
            onClick={() => void inspectRollback(revision)}>Preview rollback</ClusterButton>
        </div>
      </div>)}
    </div>
  </div>;
}


/** Admin-only projection of server-authoritative setup posture, not client checkboxes. */
export function AdminSetupChecklist({ onOpenStudioSettings, onOpenServerConfig, onOpenProjects, onOpenUserAdmin }: {
  onOpenStudioSettings?: () => void;
  onOpenServerConfig?: () => void;
  onOpenProjects?: () => void;
  onOpenUserAdmin?: () => void;
}) {
  const [state, setState] = useState<ChecklistResponse | null>(null);
  const [domainGuideOpen, setDomainGuideOpen] = useState(false);
  const [error, setError] = useState("");
  const { pending: busyId, begin: beginAction, finish: finishAction } = useClusterActionFlight();
  const refreshGeneration = useRef(createClusterLatestResponse());
  const reload = useCallback(async () => {
    const generation = refreshGeneration.current.next();
    try {
      const data = await api<ChecklistResponse>("/api/admin/setup/checklist");
      if (!refreshGeneration.current.isCurrent(generation)) return;
      setState(data); setError("");
    } catch (cause) {
      if (refreshGeneration.current.isCurrent(generation))
        setError(apiErrorPresentation(cause).message || "Setup checklist unavailable.");
    }
  }, []);
  useEffect(() => { void reload(); return () => refreshGeneration.current.invalidate(); }, [reload]);

  async function updateSkip(id: string, skipped: boolean) {
    if (!beginAction(`skip:${id}`)) return;
    refreshGeneration.current.invalidate(); // Freeze older server projections during this write.
    try {
      await api("/api/admin/setup/checklist", { method: "PATCH", body: JSON.stringify({ id, skipped }) });
      await reload();
    } catch (cause) { setError(apiErrorPresentation(cause).message || "Could not update checklist. Check its current state before retrying."); }
    finally { finishAction(`skip:${id}`); }
  }
  async function exportConfiguration() {
    if (!beginAction("export")) return;
    try {
      const bundle = await api<{ format: string; schemaVersion: number; settings: Record<string, unknown> }>("/api/admin/setup/configuration/export");
      const url = URL.createObjectURL(new Blob([JSON.stringify(bundle, null, 2)], { type: "application/json" }));
      try {
        const anchor = document.createElement("a");
        anchor.href = url;
        anchor.download = "Cluster-Studio.clusterconfig";
        anchor.click();
      } finally { window.setTimeout(() => URL.revokeObjectURL(url), 1000); }
    } catch (cause) { setError(apiErrorPresentation(cause).message || "Configuration export failed."); }
    finally { finishAction("export"); }
  }

  const destinations: Record<string, (() => void) | undefined> = {
    "studio-identity": onOpenStudioSettings,
    "studio-timezone": onOpenStudioSettings,
    "backups": onOpenServerConfig,
    "second-admin": onOpenUserAdmin,
    "first-project": onOpenProjects,
    "domains": () => setDomainGuideOpen(true),
    "owner-passkey": onOpenUserAdmin,
    "recovery-codes": onOpenUserAdmin,
  };
  return <section className="panel admin-setup-checklist-v506" aria-label="Cluster setup checklist">
    <div className="section-heading">
      <div><p className="eyebrow">Getting started</p><h3>Setup checklist</h3>
        <p className="muted tight">Live server status, not manually marked completion. Optional items can be deferred.</p></div>
      <span className="soft-pill">{state ? `${state.complete}/${state.total} ready` : "Checking…"}</span>
    </div>
    {error && <p role="alert" className="muted">{error}</p>}
    {!state && !error && <p className="muted">Checking setup status…</p>}
    {state && <>
      <p className="muted tight" role="status">{state.security.ready
        ? "Owner recovery requirements are configured."
        : `Owner security needs attention: ${state.security.missingPasskeys} Owner(s) without passkeys and ${state.security.missingRecovery} without unused recovery codes.`}
        {" "}Optional checks never override these requirements.</p>
      <div className="admin-setup-progress-v509" role="progressbar" aria-label="Configured setup checks" aria-valuemin={0} aria-valuemax={state.total} aria-valuenow={state.complete}>
        <span style={{ width: `${state.total ? (100 * state.complete / state.total) : 0}%` }} />
      </div>
      {(["Security", "Studio", "Infrastructure", "Workspace"] as const).map((group) => <div key={group} className="admin-setup-group-v509">
        <h4>{group}</h4>
        <div className="admin-setup-items-v506">{state.items.filter((item) => item.group === group).map((item) => <div className="admin-setup-item-v506" key={item.id}>
          <span aria-hidden="true">{item.status === "complete" ? "✓" : item.status === "skipped" ? "−" : "○"}</span>
          <div><strong>{item.label}</strong><small>{item.status === "complete" ? "Configured" : item.status === "skipped" ? "Deferred" : item.required ? "Required for Owner security" : "Recommended"}</small>
            <details className="admin-setup-guidance-v509"><summary>Why this matters</summary><p>{item.detail}</p><p>{item.nextStep}</p></details>
          </div>
          <div className="admin-setup-actions-v506">
            {item.status === "recommended" && destinations[item.id] && <ClusterButton type="button" variant="quiet" size="compact" onClick={destinations[item.id]}>Configure</ClusterButton>}
            {!item.required && item.status !== "complete" && <ClusterButton type="button" variant="quiet" size="compact" disabled={busyId !== null} aria-busy={busyId === `skip:${item.id}`}
              onClick={() => void updateSkip(item.id, item.status !== "skipped")}>{busyId === `skip:${item.id}` ? "Saving…" : item.status === "skipped" ? "Restore" : "Skip"}</ClusterButton>}
          </div>
        </div>)}</div>
      </div>)}
    </>}
    <div className="button-row">
      <ClusterButton type="button" variant="quiet" size="compact" onClick={() => void reload()} disabled={busyId !== null}>Refresh</ClusterButton>
      <ClusterButton type="button" variant="secondary" size="compact" disabled={busyId !== null} aria-busy={busyId === "export"} onClick={() => void exportConfiguration()}>
        {busyId === "export" ? "Exporting…" : "Export safe configuration"}
      </ClusterButton>
    </div>
    {domainGuideOpen && <DomainSetupContinuation onRefresh={() => void reload()} onClose={() => setDomainGuideOpen(false)} />}
    <AdminConfigurationImport onApplied={() => void reload()} />
  </section>;
}
