import { createHash } from "node:crypto";
import { packetRecipientCatalog, verifyPacketDerivative } from "./packet-publication.js";

/**
 * A bounded, uncompressed ZIP of detached Packet derivatives. Never consults
 * the Library source tree and never uses user-controlled paths as ZIP names.
 * The readable manifest is itself included as a detached file; the published
 * private source manifest is never bundled.
 */
type PublishedRelease = { id: string; versionLabel: string; manifestJson: string; manifestSha256: string; publishedAt: Date | string };
type Derivative = { position: number; content: Uint8Array; sha256: string; sizeBytes: number; format?: string };

const ZIP_MAX_ITEMS = 2000;
const ZIP_MAX_NOTE_BYTES = 1_048_576;
const ZIP_MAX_BYTES = 1_500_000;
const TABLE = Uint32Array.from({ length: 256 }, (_, index) => {
  let value = index;
  for (let bit = 0; bit < 8; bit++) value = (value & 1) ? (0xEDB88320 ^ (value >>> 1)) : (value >>> 1);
  return value >>> 0;
});
function crc32(data: Buffer) {
  let result = 0xffffffff;
  for (const byte of data) result = TABLE[(result ^ byte) & 0xff] ^ (result >>> 8);
  return (result ^ 0xffffffff) >>> 0;
}

function zipStoredFiles(files: { name: string; content: Buffer }[]) {
  if (!files.length || files.length > ZIP_MAX_ITEMS + 1) throw new Error("PACKET_BUNDLE_LIMIT");
  const local: Buffer[] = [];
  const central: Buffer[] = [];
  let offset = 0;
  for (const file of files) {
    // All names are generated by this module, but maintain a hard boundary
    // in case an external caller is ever added in the future.
    if (!/^(?:notes\/note-\d{4}\.(?:txt|pdf|webp)|media\/preview-\d{4}\.wav|manifest\.json)$/.test(file.name)) throw new Error("PACKET_BUNDLE_PATH_INVALID");
    const name = Buffer.from(file.name, "utf8");
    const size = file.content.length;
    const checksum = crc32(file.content);
    const header = Buffer.alloc(30);
    header.writeUInt32LE(0x04034b50, 0);
    header.writeUInt16LE(20, 4); // version
    header.writeUInt16LE(0x0800, 6); // UTF-8
    header.writeUInt16LE(0, 8); // STORE: no decompression bombs
    header.writeUInt32LE(checksum, 14);
    header.writeUInt32LE(size, 18);
    header.writeUInt32LE(size, 22);
    header.writeUInt16LE(name.length, 26);
    local.push(header, name, file.content);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4);
    entry.writeUInt16LE(20, 6);
    entry.writeUInt16LE(0x0800, 8);
    entry.writeUInt32LE(checksum, 16);
    entry.writeUInt32LE(size, 20);
    entry.writeUInt32LE(size, 24);
    entry.writeUInt16LE(name.length, 28);
    entry.writeUInt32LE(offset, 42);
    central.push(entry, name);
    offset += header.length + name.length + size;
    if (offset > ZIP_MAX_BYTES) throw new Error("PACKET_BUNDLE_LIMIT");
  }
  const centralLength = central.reduce((sum, data) => sum + data.length, 0);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralLength, 12);
  end.writeUInt32LE(offset, 16);
  if (offset + centralLength + end.length > ZIP_MAX_BYTES) throw new Error("PACKET_BUNDLE_LIMIT");
  return Buffer.concat([...local, ...central, end]);
}

export function buildPacketDerivativeBundle(release: PublishedRelease, artifacts: Derivative[]) {
  // Verify the sealed release BEFORE using any published index/title fields.
  const catalog = packetRecipientCatalog(release);
  if (!artifacts.length) throw new Error("PACKET_DERIVATIVE_NOT_FOUND");
  if (artifacts.length > ZIP_MAX_ITEMS) throw new Error("PACKET_BUNDLE_LIMIT");
  const seen = new Set<number>();
  const files: { name: string; content: Buffer }[] = [];
  const entries: { position: number; path: string; sha256: string; sizeBytes: number; format: string; deliveryKind: "excerpt" | "detached_copy" }[] = [];
  let total = 0;
  for (const artifact of [...artifacts].sort((a, b) => a.position - b.position)) {
    if (!Number.isSafeInteger(artifact.position) || artifact.position < 1 || artifact.position > catalog.contents.length || seen.has(artifact.position))
      throw new Error("PACKET_DERIVATIVE_INVALID");
    seen.add(artifact.position);
    const bytes = verifyPacketDerivative(artifact);
    total += bytes.length;
    if (total > ZIP_MAX_NOTE_BYTES) throw new Error("PACKET_BUNDLE_LIMIT");
    const format = artifact.format || "txt";
    if (!["txt", "pdf", "webp", "wav"].includes(format)) throw new Error("PACKET_DERIVATIVE_FORMAT_INVALID");
    const path = format === "wav" ? `media/preview-${String(artifact.position).padStart(4, "0")}.wav` : `notes/note-${String(artifact.position).padStart(4, "0")}.${format}`;
    files.push({ name: path, content: bytes });
    entries.push({ position: artifact.position, path, sha256: createHash("sha256").update(bytes).digest("hex"), sizeBytes: bytes.length, format, deliveryKind: format === "wav" ? "excerpt" : "detached_copy" });
  }
  const manifest = {
    schema: 1, format: "cluster-packet-detached-derivatives", releaseId: release.id,
    versionLabel: catalog.versionLabel, sourceManifestSha256: catalog.manifestSha256,
    publicationWatermarkLabel: catalog.publicationWatermarkLabel || "",
    deliveredCount: entries.length, unavailableCount: catalog.contents.length - entries.length,
    entries,
  };
  const manifestBytes = Buffer.from(JSON.stringify(manifest, null, 2) + "\n", "utf8");
  files.unshift({ name: "manifest.json", content: manifestBytes });
  const bytes = zipStoredFiles(files);
  return { bytes, count: entries.length, sha256: createHash("sha256").update(bytes).digest("hex") };
}
