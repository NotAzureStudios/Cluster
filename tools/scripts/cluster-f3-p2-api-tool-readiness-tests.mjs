function load(name) {
  const result = ts.transpileModule(read(name), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }, reportDiagnostics: true });
  assert.equal(result.diagnostics?.length || 0, 0, `${name} syntactically valid`);
  const exports = {};
  vm.runInNewContext(result.outputText, { exports, Date, Math, Number, String, JSON, Map, Set, Error, Promise, Object, Boolean }, { filename: name });
  return exports;
}
