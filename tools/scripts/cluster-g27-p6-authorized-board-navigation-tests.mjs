import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';
import path from 'node:path';
const require=createRequire(import.meta.url);
const ts=(()=>{try{return require('typescript')}catch{return require(path.join(execFileSync('npm',['root','-g'],{encoding:'utf8'}).trim(),'typescript/lib/typescript.js'))}})();
const read=p=>readFileSync(new URL('../../'+p,import.meta.url),'utf8');
const file='packages/renderer/src/features/workflow/authorized-board-navigation.ts';
const mod={exports:{}};
vm.runInNewContext(ts.transpileModule(read(file),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module:mod,exports:mod.exports},{filename:file});
const {resolveAuthorizedBoardNavigation}=mod.exports;
let n=0;
const check=async(name, fn)=>{await fn();n++;console.log('PASS '+name)};
const target={screen:'board',boardId:'b1',projectId:'stale'};
const resolve=(t=target,options={})=>resolveAuthorizedBoardNavigation(t,{read:async(id)=>{if(options.fail)throw Error('403');return options.value===undefined?{id,projectId:'current'}:options.value},isCurrent:options.current||(()=>true)});
await check('current project supersedes stale link',async()=>assert.equal((await resolve()).projectId,'current'));
await check('standalone board clears stale project',async()=>assert.equal((await resolve(target,{value:{id:'b1',projectId:null}})).projectId,null));
await check('mismatched identity fails closed',async()=>assert.equal(await resolve(target,{value:{id:'b2',projectId:'x'}}),null));
await check('revoked board fails closed',async()=>assert.equal(await resolve(target,{fail:true}),null));
await check('missing board fails closed',async()=>assert.equal(await resolve(target,{value:null}),null));
await check('late navigation fails closed',async()=>assert.equal(await resolve(target,{current:()=>false}),null));
await check('invalid id fails closed',async()=>assert.equal(await resolve({...target,boardId:' '}),null));
await check('oversized id fails closed',async()=>assert.equal(await resolve({...target,boardId:'x'.repeat(201)}),null));
await check('card links retain separate Card resolver',async()=>assert.equal(await resolve({...target,inspectScope:'card',inspectId:'c1'}),null));
await check('missing placement fails closed',async()=>assert.equal(await resolve(target,{value:{id:'b1'}}),null));
await check('malformed placement fails closed',async()=>assert.equal(await resolve(target,{value:{id:'b1',projectId:77}}),null));
const app=read('packages/renderer/src/features/application/ClusterApplication.tsx');
await check('central application invokes Board resolver',async()=>assert.match(app,/resolveAuthorizedBoardNavigation\(incoming, \{/));
await check('fresh Board read disables cached responses',async()=>assert.match(app,/queryApi<AuthorizedBoardRead>[\s\S]*?force: true, persist: false, staleWhileRevalidate: false/));
await check('Board admission occurs before applying linked work',async()=>assert.ok(app.indexOf('resolveAuthorizedBoardNavigation(incoming')<app.lastIndexOf('applyLinkedWork(incoming);')));
console.log(`${n}/${n} authorized Board navigation checks passed`);
