await check('deleted project denied',async()=>assert.equal(await resolve(target,{value:null}),null));
await check('mismatched project denied',async()=>assert.equal(await resolve(target,{value:{id:'p2'}}),null));
await check('stale response denied',async()=>assert.equal(await resolve(target,{current:()=>false}),null));
await check('missing ID denied',async()=>assert.equal(await resolve({...target,projectId:null}),null));
await check('oversized ID denied',async()=>assert.equal(await resolve({...target,projectId:'x'.repeat(201)}),null));
await check('other route untouched',async()=>assert.equal(await resolve({...target,screen:'board'}),null));
const app=read('packages/renderer/src/features/application/ClusterApplication.tsx');
