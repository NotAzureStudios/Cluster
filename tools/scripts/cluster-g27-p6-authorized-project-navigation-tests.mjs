import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
import vm from 'node:vm';
import path from 'node:path';
const require=createRequire(import.meta.url);
const ts=(()=>{try{return require('typescript')}catch{return require(path.join(execFileSync('npm',['root','-g'],{encoding:'utf8'}).trim(),'typescript/lib/typescript.js'))}})();
const read=p=>readFileSync(new URL('../../'+p,import.meta.url),'utf8');
const file='packages/renderer/src/features/workflow/authorized-project-navigation.ts';
const mod={exports:{}};
vm.runInNewContext(ts.transpileModule(read(file),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module:mod,exports:mod.exports},{filename:file});
const {resolveAuthorizedProjectNavigation}=mod.exports;
const target={screen:'project',projectId:'p1',projectTab:'boards'};
const resolve=(t=target,o={})=>resolveAuthorizedProjectNavigation(t,{read:async(id)=>{if(o.fail)throw Error('403');return o.value===undefined?{id}:o.value},isCurrent:o.current||(()=>true)});
let n=0;const check=async(title,fn)=>{await fn();n++;console.log('PASS '+title)};
