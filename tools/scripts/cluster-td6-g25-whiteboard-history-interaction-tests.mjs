import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const root=resolve(import.meta.dirname,'../..');
const source=readFileSync(resolve(root,'packages/renderer/src/features/whiteboards/whiteboard-history-shortcuts.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};new Function('module','exports',output)(mod,mod.exports);
const {whiteboardHistoryShortcut:direction,canUseWhiteboardHistory:available,whiteboardHistoryTargetContext:context}=mod.exports;
let count=0;
const check=(name,fn)=>{fn();count++;console.log('PASS G25 Whiteboard '+name)};
const key=(input)=>direction({key:'z',ctrlKey:true,metaKey:false,altKey:false,shiftKey:false,editingText:false,...input});
check('canvas Ctrl+Z selects local/saved undo',()=>assert.equal(key({}),'undo'));
check('Ctrl+Shift+Z selects redo',()=>assert.equal(key({shiftKey:true}),'redo'));
check('Ctrl+Y selects redo',()=>assert.equal(key({key:'Y'}),'redo'));
check('macOS Cmd+Z selects undo',()=>assert.equal(key({metaKey:true,ctrlKey:false}),'undo'));
check('text-input Ctrl+Z belongs to native editor',()=>assert.equal(key({editingText:true}),null));
check('contenteditable Cmd+Shift+Z belongs to native editor',()=>assert.equal(key({metaKey:true,ctrlKey:false,editingText:true,shiftKey:true}),null));
check('Alt modified key is not hijacked',()=>assert.equal(key({altKey:true}),null));
check('unmodified key does not act',()=>assert.equal(key({ctrlKey:false}),null));
const state=(x)=>available({saving:false,localCount:0,savedAvailable:true,localDirty:false,pendingRemote:false,queuedSync:false,...x});
check('saved undo enabled when clean and online',()=>assert.equal(state({}),true));
check('dirty working copy blocks server replay',()=>assert.equal(state({localDirty:true}),false));
check('pending collaborator conflict blocks server replay',()=>assert.equal(state({pendingRemote:true}),false));
check('queued offline work blocks server replay',()=>assert.equal(state({queuedSync:true}),false));
check('saving blocks both local and server history',()=>assert.equal(state({saving:true,localCount:1}),false));
check('unsaved local history works while server replay blocked',()=>assert.equal(state({localDirty:true,localCount:1,pendingRemote:true}),true));
check('no local/saved history disables controls',()=>assert.equal(state({savedAvailable:false}),false));
const page=readFileSync(resolve(root,'packages/renderer/src/features/whiteboards/WhiteboardWorkspacePage.tsx'),'utf8');
