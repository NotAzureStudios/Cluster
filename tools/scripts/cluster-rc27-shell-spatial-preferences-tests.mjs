const preview=read('packages/renderer/src/features/settings/AppearanceShellPreview.tsx');
const runtime=read('packages/renderer/src/features/application/modules/ApplicationSidebar.tsx');
const shell=read('packages/renderer/src/features/shell/shell-spatial-rc27.css');
const app=read('packages/renderer/src/features/application/ClusterApplication.tsx');
const workspace=read('packages/renderer/src/styles/workspace-contract.css');
const storage=read('packages/renderer/src/features/application/modules/application-foundation.tsx');
assert.match(contract, /sidebarItemStyle\?: "soft" \| "divided" \| "outlined"/);
assert.match(api,/sidebarItemStyle: z\.enum\(\["soft", "divided", "outlined"\]\)\.optional\(\)/);
assert.match(visual,/sidebarItemStyle: choice\(instance\.sidebarItemStyle,/);
assert.match(visual,/root\.dataset\.sidebarItemStyle = context\.sidebarItemStyle/);
assert.match(visual,/sidebarItemStyle: "outlined"/);
assert.match(storage, /"sidebarItemStyle"/);
assert.match(settings, /patch\("sidebarItemStyle", option\)/);
assert.match(preview,/data-sidebar-item-style=\{context\.sidebarItemStyle\}/);
