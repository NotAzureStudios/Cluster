assert.match(workspace, /--cluster-sidebar-current-width: 232px/);
assert.match(shell, /#cluster-sidebar\.cluster-sidebar[\s\S]*?border-right: 1px/);
for (const style of ['outlined','divided','soft']) assert.ok(shell.includes(`data-sidebar-item-style="${style}"`));
assert.match(shell,/\.app-shell\.shell-unified-v3430 > \.content-shell \{[\s\S]*?overflow-y: auto/);
assert.match(shell,/\.visual-overhaul-v139 \.page \{[\s\S]*?max-width:100%/);
assert.match(app,/import "\.\.\/shell\/shell-spatial-rc27\.css"/);
for (const p of ['packages/renderer/src/features/application/application-models/settings-server.ts','apps/server/src/domains/users/user-preference-routes.ts','packages/renderer/src/core/visual-system.ts','packages/renderer/src/features/settings/AccountSettingsPage.tsx','packages/renderer/src/features/settings/AppearanceShellPreview.tsx','packages/renderer/src/features/application/modules/ApplicationSidebar.tsx','packages/renderer/src/features/application/ClusterApplication.tsx','packages/renderer/src/features/application/modules/application-foundation.tsx']) {
 const parsed=ts.createSourceFile(p,read(p),ts.ScriptTarget.Latest,true,p.endsWith('.tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);
 assert.equal(parsed.parseDiagnostics.length,0,`${p}: ${parsed.parseDiagnostics.map(d=>ts.flattenDiagnosticMessageText(d.messageText,' ')).join(', ')}`);
}
