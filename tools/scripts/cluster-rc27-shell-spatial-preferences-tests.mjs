import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';
const root = path.resolve(import.meta.dirname, '../..');
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const require=createRequire(import.meta.url);
const ts=(()=>{try{return require('typescript')}catch{return require(path.join(execFileSync('npm',['root','-g'],{encoding:'utf8'}).trim(),'typescript'))}})();
const contract=read('packages/renderer/src/features/application/application-models/settings-server.ts');
const api=read('apps/server/src/domains/users/user-preference-routes.ts');
const visual=read('packages/renderer/src/core/visual-system.ts');
