#!/usr/bin/env node
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const read=x=>readFileSync(x,'utf8');
const file='apps/server/src/domains/inventory/inventory-key-readiness.ts';
const code=ts.transpileModule(read(file),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const shape={trim(){return this},min(){return this},max(){return this},optional(){return this},strict(){return this},parse(x){return x}};
const module={exports:{}};
vm.runInNewContext(code,{module,exports:module.exports,require:n=>n==='zod'?{z:{string:()=>shape,object:()=>shape}}:require(n), Date,Map,Set,Error,console},{filename:file});
const {keyCustodyReason}=module.exports;
const now=new Date('2026-11-08T12:00:00Z');
const inDays=n=>new Date(now.getTime()+n*86400000);
const base={expiresAt:inDays(25),secret:{revokedAt:null,expiresAt:inDays(25)}};
const person={archived:false,accountState:'ACTIVE',accessExpiresAt:inDays(25)};
let count=0;
const check=(name,expect,actual)=>{assert.equal(actual,expect,name);count++;console.log('PASS Batch E '+name)};
check('far-future healthy','no_known_custody_blocker',keyCustodyReason(base,'active',person,now));
check('key expires in six days','key_expires_soon',keyCustodyReason({...base,expiresAt:inDays(6)},'active',person,now));
check('key exactly seven days','key_expires_soon',keyCustodyReason({...base,expiresAt:inDays(7)},'active',person,now));
check('key eight days','no_known_custody_blocker',keyCustodyReason({...base,expiresAt:inDays(8)},'active',person,now));
check('Vault expiry within seven days','vault_expires_soon',keyCustodyReason({...base,secret:{...base.secret,expiresAt:inDays(4)}},'active',person,now));
check('account expires within seven days','recipient_access_expires_soon',keyCustodyReason(base,'active',{...person,accessExpiresAt:inDays(3)},now));
check('expired key overrides advisory','key_expired',keyCustodyReason({...base,expiresAt:inDays(-1)},'active',person,now));
check('revoked Vault overrides advisory','vault_revoked',keyCustodyReason({...base,expiresAt:inDays(1),secret:{...base.secret,revokedAt:now}},'active',person,now));
check('inactive account overrides advisory','recipient_inactive',keyCustodyReason({...base,expiresAt:inDays(1)},'active',{...person,archived:true},now));
check('pool closed overrides advisory','pool_closed',keyCustodyReason({...base,expiresAt:inDays(1)},'closed',person,now));
check('null expiry does not alarm','no_known_custody_blocker',keyCustodyReason({expiresAt:null,secret:{revokedAt:null,expiresAt:null}},'active',{...person,accessExpiresAt:null},now));
const route=read('apps/server/src/domains/inventory/studio-inventory-vault-routes.ts');
assert.match(route,/studioVaultSecret\.count\(\{ where: \{ revokedAt: null, expiresAt: \{ gt: now, lte: soon \} \} \}\)/);count++;
assert.match(route,/studioVaultSecret\.count\(\{ where: \{ revokedAt: null, expiresAt: \{ lte: now \} \} \}\)/);count++;
assert.match(route,/vaultExpiring, vaultPastDue \};/);count++;
const ui=read('packages/renderer/src/features/inventory/InventoryKeyCustodyReview.tsx');
assert.match(ui,/recipient_access_expires_soon/);count++;
assert.match(ui,/vault_expires_soon/);count++;
assert.match(read('packages/renderer/src/features/settings/StudioInventoryVaultPanel.tsx'),/attention\.vaultPastDue/);count++;
console.log(`G26 Batch E expiry checks: ${count}/${count} passed`);
